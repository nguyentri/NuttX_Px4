#define GPIO_OUTPUT_LOW           	    (0)                     /* Output low (default) */
#define GPIO_PULLUP               	    (1 << R_PFS_PCR)       /* Enable pull-up */
#define GPIO_OPENDRAIN            	    (1 << R_PFS_NCODR)     /* Open drain output */

